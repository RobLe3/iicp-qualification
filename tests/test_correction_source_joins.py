import copy,sys,unittest
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT/'scripts'))
import correction_source_joins as r
class Controls(unittest.TestCase):
 def setUp(self):self.x=r.load()
 def reject(self,fn):
  fn(self.x)
  with self.assertRaises(Exception):r.validate(self.x)
 def test_positive(self):self.assertTrue(r.check())
 def test_deterministic(self):self.assertEqual(r.render(self.x),r.render(copy.deepcopy(self.x)))
 def test_candidate(self):self.reject(lambda x:x.update(candidate_digest='sha256:'+'0'*64))
 def test_state_promotion(self):self.reject(lambda x:x.update(state='FULL_REFERENCE_ACCEPTED'))
