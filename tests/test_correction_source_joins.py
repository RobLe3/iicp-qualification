 def test_wrong_source_role(self):self.reject(lambda x:x['rows'][0]['source_refs'][0].update(evidence_role='EXECUTED_TEST'))
 def test_wrong_source_commit(self):self.reject(lambda x:x['rows'][0]['source_refs'][0].update(source_commit='0'*40))
 def test_wrong_source_digest(self):self.reject(lambda x:x['rows'][0]['source_refs'][0].update(file_sha256='malformed'))
