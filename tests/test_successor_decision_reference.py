import copy,sys,unittest
from pathlib import Path
from jsonschema.exceptions import ValidationError
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'scripts'))
import successor_decision_reference as ref
class SuccessorDecisionReferenceTests(unittest.TestCase):
 def setUp(self):self.value=ref.load();self.original=copy.deepcopy(self.value)
 def reject(self):
  self.assertNotEqual(ref.canonical(self.value),ref.canonical(self.original),'negative fixture must change representation')
  with self.assertRaises((ValueError,ValidationError)):ref.validate(self.value)
 def test_positive_control(self):self.assertTrue(ref.check())
 def test_deterministic_render(self):self.assertEqual(ref.render(self.value),ref.render(copy.deepcopy(self.value)))
 def test_render_18_advisory_rows(self):self.assertEqual(sum('RUSTSEC-' in r for r in ref.render(self.value).splitlines() if r.startswith('| ')),18)
 def test_noop_negative_guard(self):
  with self.assertRaisesRegex(AssertionError,'must change'):self.reject()
 def test_credit_inflation(self):self.value['qualification_credit']=1;self.reject()
 def test_credit_bool_not_integer(self):self.value['qualification_credit']=False;self.reject()
 def test_component_float_not_integer(self):self.value['counts']['components']=6.0;self.reject()
 def test_freeze_overclaim(self):self.value['baseline_frozen']=True;self.reject()
 def test_candidate_generation(self):self.value['candidate_generated']=True;self.reject()
 def test_cloud_authority(self):self.value['cloud_authorized']=True;self.reject()
 def test_qualification_authority(self):self.value['qualification_execution_authorized']=True;self.reject()
 def test_package_publication_authority(self):self.value['package_publication_authorized']=True;self.reject()
 def test_candidate_substitution(self):self.value['original_candidate_manifest_digest']='sha256:'+'0'*64;self.reject()
 def test_source_selection(self):self.value['component_source_rows'][0]['successor_source_selected']=True;self.reject()
 def test_artifact_selection(self):self.value['artifact_slots'][0]['successor_artifact_sha256']='sha256:'+'0'*64;self.reject()
 def test_duplicate_slot(self):self.value['artifact_slots'][0]=copy.deepcopy(self.value['artifact_slots'][1]);self.reject()
 def test_missing_component(self):self.value['component_source_rows'].pop();self.reject()
 def test_path_count_inflation(self):self.value['counts']['changed_component_paths']+=1;self.reject()
 def test_helper_as_workload(self):self.value['binding_rehearsal']['qualification_workloads']=64;self.reject()
 def test_helper_scope_overclaim(self):self.value['binding_rehearsal']['full_receipt_validation_pass']=True;self.reject()
 def test_control_as_new_receipt(self):self.value['binding_rehearsal']['new_receipts_issued']=64;self.reject()
 def test_original_modified(self):self.value['binding_rehearsal']['original_receipts_modified']=True;self.reject()
 def test_patched_rustls_false_positive(self):self.value['selected_advisory_source_rows'][0]['versions']['qualified']['range_status']='AFFECTED_VERSION_RANGE_ONLY_NOT_EXPLOITABILITY';self.reject()
 def test_source_range_as_exploit(self):self.value['selected_advisory_source_rows'][0]['exploitation_or_live_exposure_claimed']=True;self.reject()
 def test_advisory_condition_removed(self):self.value['selected_advisory_source_rows'][0]['applicability_condition']='';self.reject()
 def test_advisory_source_tamper(self):self.value['selected_advisory_source_rows'][0]['primary_source']['sha256']='0'*64;self.reject()
 def test_dependency_floor_as_full_audit(self):self.value['maintained_source_floor_checks'][0]['full_security_audit']=True;self.reject()
 def test_private_count_added(self):self.value['counts']['private_sdk_source_options_held']=2;self.reject()
 def test_private_locator(self):self.value['limits'].append('/Users/synthetic/private-marker');self.reject()
 def test_private_authority_blob(self):self.value['authorization.json']={'synthetic_marker':'not-a-secret'};self.reject()
 def test_controlled_gate_bypass(self):self.value['decision_gates'][1]['status']='CLEARED';self.reject()
 def test_sentinel_duplicate_credit(self):self.value['formal_verification_projection']['sentinel_adds_campaign_credit']=True;self.reject()
 def test_unknown_assumption(self):self.value['arbitrary_claim']='new evidence is qualified';self.reject()
 def test_source_observation_date_tamper(self):self.value['source_observation_intervals'][0]['observed_at']='2026-11-08T00:00:00Z';self.reject()
if __name__=='__main__':unittest.main()
