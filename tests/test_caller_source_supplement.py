import copy,json,sys,unittest
from pathlib import Path
from jsonschema import ValidationError
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'scripts'))
import finite_catalog_reference as m
class CallerSupplementTests(unittest.TestCase):
 def reject(self,change):
  value=copy.deepcopy(m.load_callers());change(value)
  with self.assertRaises((ValueError,ValidationError)):m.validate_callers(value)
 def test_01_fixed_public_positive(self):self.assertTrue(m.validate_callers(m.load_callers()))
 def test_02_generated_files(self):self.assertTrue(m.check_callers())
 def test_03_predecessor_still_verified(self):self.assertTrue(m.check())
 def test_04_deterministic_render(self):self.assertEqual(m.render_callers(m.load_callers()),m.render_callers(json.loads(json.dumps(m.load_callers()))))
 def test_05_counts(self):self.assertEqual(sum(r['existing_reference_count'] for r in m.load_callers()['caller_cases']),206)
 def test_06_source_questions_not_all_runtime_contracts(self):self.assertEqual(m.load_callers()['counts']['bounded_source_questions_resolved'],4)
 def test_07_no_foreign_candidate(self):self.reject(lambda v:v.update(candidate_digest='sha256:'+'0'*64))
 def test_08_no_foreign_source(self):self.reject(lambda v:v['sources'][0].update(commit='0'*40))
 def test_09_no_missing_case(self):self.reject(lambda v:v['caller_cases'].pop())
 def test_10_no_duplicate_case(self):self.reject(lambda v:v['caller_cases'].__setitem__(1,copy.deepcopy(v['caller_cases'][0])))
 def test_11_no_reference_inflation(self):self.reject(lambda v:v['caller_cases'][0].update(existing_reference_count=5590))
 def test_12_no_new_credit(self):self.reject(lambda v:v['boundaries'].update(new_qualification_credit=1))
 def test_13_bool_not_credit(self):self.reject(lambda v:v['boundaries'].update(new_qualification_credit=False))
 def test_14_no_history_change(self):self.reject(lambda v:v['boundaries'].update(original_outcomes_changed=True))
 def test_15_no_whole_catalog_conformance(self):self.reject(lambda v:v['boundaries'].update(whole_catalog_conformance_established=True))
 def test_16_no_frozen_reference(self):self.reject(lambda v:v['boundaries'].update(corrected_reference_frozen=True))
 def test_17_no_historical_completeness(self):self.reject(lambda v:v['boundaries'].update(historical_inventory_complete=True))
 def test_18_no_defect_clearance(self):self.reject(lambda v:v['boundaries'].update(product_defect_clearance_established=True))
 def test_19_no_external_interop(self):self.reject(lambda v:v['boundaries'].update(independent_interoperability_established=True))
 def test_20_no_certification(self):self.reject(lambda v:v['boundaries'].update(external_certification_established=True))
 def test_21_no_release_or_intake(self):self.reject(lambda v:v['boundaries'].update(release_or_intake_authorized=True))
 def test_22_no_private_disclosure(self):self.reject(lambda v:v['boundaries'].update(private_coordination_or_source_concerns_distributed=True))
 def test_23_no_controlled_wording_field(self):self.reject(lambda v:v['caller_cases'][0].update(exact_catalog_expectation='synthetic'))
 def test_24_no_runtime_design_inflation(self):self.reject(lambda v:v['counts'].update(new_reference_executions=5))
 def test_25_no_release_gate_pass(self):self.reject(lambda v:v['release_horizon'].update(new_readiness_gate_passes=1))
 def test_26_no_legal_claim(self):self.reject(lambda v:v['release_horizon'].update(legal_applicability_assessed=True))
 def test_27_no_review_slot_promotion(self):self.reject(lambda v:v['release_horizon']['qualified_review_slot'].update(review_present=True))
 def test_28_no_issue_closure(self):self.reject(lambda v:v['release_horizon']['prerequisite_owner_states'][0].update(state='CLOSED'))
 def test_29_no_private_path(self):self.reject(lambda v:v['limitations'].append('/Users/synthetic/marker'))
 def test_30_no_private_advisory_marker(self):self.reject(lambda v:v['limitations'].append('GHSA-synthetic-marker'))
 def test_31_no_cloud_identity(self):self.reject(lambda v:v['limitations'].append('arn:aws:synthetic'))
 def test_32_no_unapproved_source_role(self):self.reject(lambda v:v['sources'][0].update(role='CURRENT_PUBLIC_MAIN_IPC_STARTUP'))
if __name__=='__main__':unittest.main(verbosity=2)
